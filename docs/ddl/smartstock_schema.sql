CREATE TABLE IF NOT EXISTS categoria (
    id_categoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(100) NOT NULL,
    descripcion  VARCHAR(255),
    estado       BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS rol (
    id_rol      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(50) NOT NULL UNIQUE,
    descripcion VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS usuario (
    id_usuario    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR(100) NOT NULL,
    apellido      VARCHAR(100),
    correo        VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    estado        BOOLEAN NOT NULL DEFAULT TRUE,
    id_rol        BIGINT NOT NULL REFERENCES rol(id_rol)
);

CREATE TABLE IF NOT EXISTS producto (
    id_producto  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(150) NOT NULL,
    descripcion  VARCHAR(255),
    codigo       VARCHAR(50) UNIQUE,
    precio       NUMERIC(12,2) CHECK (precio IS NULL OR precio >= 0),
    stock_minimo INT NOT NULL DEFAULT 0 CHECK (stock_minimo >= 0),
    estado       BOOLEAN NOT NULL DEFAULT TRUE,
    id_categoria BIGINT REFERENCES categoria(id_categoria)
);

CREATE TABLE IF NOT EXISTS inventario (
    id_inventario       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cantidad_actual     INT NOT NULL DEFAULT 0 CHECK (cantidad_actual >= 0),
    ubicacion           VARCHAR(100),
    fecha_actualizacion TIMESTAMP DEFAULT now(),
    id_producto         BIGINT NOT NULL UNIQUE REFERENCES producto(id_producto)
);

CREATE TABLE IF NOT EXISTS proveedor (
    id_proveedor BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(150) NOT NULL,
    telefono     VARCHAR(30),
    correo       VARCHAR(150),
    estado       BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS movimiento_inventario (
    id_movimiento   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_movimiento VARCHAR(20) NOT NULL CHECK (tipo_movimiento IN ('entrada','salida','ajuste')),
    cantidad        INT NOT NULL CHECK (cantidad >= 0),
    fecha           TIMESTAMP NOT NULL DEFAULT now(),
    motivo          VARCHAR(255),
    id_producto     BIGINT NOT NULL REFERENCES producto(id_producto),
    id_usuario      BIGINT NOT NULL REFERENCES usuario(id_usuario)
);

CREATE TABLE IF NOT EXISTS alerta (
    id_alerta   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo        VARCHAR(30) NOT NULL CHECK (tipo IN ('stock_minimo')),
    mensaje     VARCHAR(255) NOT NULL,
    fecha       TIMESTAMP NOT NULL DEFAULT now(),
    estado      VARCHAR(20) NOT NULL DEFAULT 'pendiente' CHECK (estado IN ('pendiente','resuelta')),
    id_producto BIGINT NOT NULL REFERENCES producto(id_producto)
);

CREATE TABLE IF NOT EXISTS reposicion (
    id_reposicion       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cantidad_sugerida   INT NOT NULL CHECK (cantidad_sugerida >= 0),
    cantidad_solicitada INT CHECK (cantidad_solicitada IS NULL OR cantidad_solicitada > 0),
    fecha               TIMESTAMP NOT NULL DEFAULT now(),
    estado              VARCHAR(20) NOT NULL DEFAULT 'sugerida' CHECK (estado IN ('sugerida','confirmada','rechazada')),
    modelo_prediccion   VARCHAR(50),
    demanda_estimada    DOUBLE PRECISION,
    nota                VARCHAR(255),
    id_producto         BIGINT NOT NULL REFERENCES producto(id_producto),
    id_proveedor        BIGINT REFERENCES proveedor(id_proveedor)
);

CREATE TABLE IF NOT EXISTS auditoria (
    id_auditoria      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    accion            VARCHAR(50) NOT NULL,
    tabla_afectada    VARCHAR(50),
    registro_afectado BIGINT,
    fecha             TIMESTAMP NOT NULL DEFAULT now(),
    descripcion       VARCHAR(500),
    id_usuario        BIGINT NOT NULL REFERENCES usuario(id_usuario)
);

CREATE INDEX IF NOT EXISTS idx_producto_categoria ON producto(id_categoria);
CREATE INDEX IF NOT EXISTS idx_movimiento_producto_fecha ON movimiento_inventario(id_producto, fecha);
CREATE INDEX IF NOT EXISTS idx_movimiento_fecha ON movimiento_inventario(fecha);
CREATE INDEX IF NOT EXISTS idx_alerta_producto_estado ON alerta(id_producto, estado);
CREATE INDEX IF NOT EXISTS idx_reposicion_producto_estado ON reposicion(id_producto, estado);
CREATE INDEX IF NOT EXISTS idx_auditoria_fecha ON auditoria(fecha);

